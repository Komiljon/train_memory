/// Тип колоды: влияет на каталог лиц и отрисовку карт на поле.
enum DeckKind {
  /// Тематические иконки природы (звезда, луна, vish и т.д.).
  nature,

  /// Классические игральные карты: ранг + масть.
  playingCards,

  /// Животные: эмодзи на лице карты.
  animals,

  /// Фрукты и ягоды: эмодзи на лице карты.
  fruits,

  /// Цифры 1–8: крупный глиф + подпись.
  numbers,

  /// Транспорт: эмодзи на лице карты.
  transport,

  /// Геометрические фигуры: Unicode-символы.
  shapes,
}
