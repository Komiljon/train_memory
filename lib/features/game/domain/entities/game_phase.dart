/// Фаза хода: UI блокирует тапы в resolving/won.
enum GamePhase {
  /// Можно открыть первую или вторую карту.
  idle,

  /// Открыта ровно одна несовпавшая карта — ждём вторую.
  awaitingSecond,

  /// Две открытые карты не совпали — пауза перед закрытием.
  resolving,

  /// Все пары найдены.
  won,
}
